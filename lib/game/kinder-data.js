/** מסלול המסע: אות, אות, מספר... ואחרי כל 4 אותיות – חגיגה בכפר (חזרה על הכול) */
export function buildPath(order) {
  const path = []; let n = 1, li = 0;
  for (const l of order) {
    path.push({ k: 'l', v: l }); li++;
    if (li % 2 === 0 && n <= 10) path.push({ k: 'n', v: n++ });
    if (li % 4 === 0) path.push({ k: 'party', v: li / 4 });
  }
  while (n <= 10) path.push({ k: 'n', v: n++ });
  path.push({ k: 'party', v: 99 });
  return path;
}

