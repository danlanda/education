/** כל המשפטים שאפשר להשמיע (בשביל הקול הטבעי בשרת – הוא מקריא רק משפטים מהמשחק) */
export function kinderLines() {
  const out = new Set([V.hello, V.home, V.pickLetters, V.pickNumbers, V.memory, V.countPick, V.feedNo, V.more, V.less, V.sticker, V.again, V.album, V.sleep, V.tooMany, V.tooFew, ...PRAISE, ...RETRY, ...NUM]);
  for (let n = 1; n <= 10; n++) for (const p of PRAISE) out.add(V.numOk(n, p));
  for (let a = 1; a <= 9; a++) for (let b = 1; a + b <= 10; b++) for (const p of PRAISE) out.add(V.addOk(a, b, p));
  for (const L of KLETTERS) {
    out.add(L.name); out.add(V.memOk(L)); out.add(V.trace(L)); out.add(V.traceOk(L)); out.add(V.firstNo(L)); out.add(V.newLetter(L));
    for (const [w] of L.words) { out.add(w); out.add(V.balloons(L, w)); out.add(V.firstQ(w)); out.add(V.firstOk(L, w)); }
  }
  for (const [t] of THINGS) { out.add(V.count(t)); for (let n = 1; n <= 10; n++) out.add(V.feed(n, t)); for (let a = 1; a <= 9; a++) for (let b = 1; a + b <= 10; b++) out.add(V.add(a, b, t)); }
  for (let n = 1; n <= 10; n++) out.add(V.numpop(n));
  return out;
}
