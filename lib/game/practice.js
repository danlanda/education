const fill = (t, o) => t.replace(/\{(\w)\}/g, (_, k) => o[k]);

/** בעיה אחת לפי רמה (1–5). מחזיר { eq } לתרגיל או { text } לבעיה מילולית, ו־answer */
export function makeProblem(level, word = false) {
  const L = Math.max(1, Math.min(5, level));
  if (word && L >= 2) {
    const kind = L >= 5 ? 'two' : pickOne(L >= 3 ? ['add', 'sub', 'mul', 'div'] : ['add', 'sub', 'mul']);
    if (kind === 'add') { const a = R(L >= 3 ? 120 : 15, L >= 3 ? 480 : 60), b = R(L >= 3 ? 110 : 12, L >= 3 ? 450 : 39); return { text: fill(pickOne(WORD.add), { a, b }), answer: a + b }; }
    if (kind === 'sub') { const a = R(L >= 3 ? 300 : 40, L >= 3 ? 900 : 99), b = R(L >= 3 ? 120 : 11, a - 10); return { text: fill(pickOne(WORD.sub), { a, b }), answer: a - b }; }
    if (kind === 'mul') { const a = R(3, L >= 4 ? 12 : 9), b = R(L >= 4 ? 6 : 2, 9); return { text: fill(pickOne(WORD.mul), { a, b }), answer: a * b }; }
    if (kind === 'div') { const b = R(2, 9), q = R(3, 10); return { text: fill(pickOne(WORD.div), { a: b * q, b }), answer: q }; }
    // שני שלבים
    const t = pickOne(WORD.two);
    if (t.includes('נִשְׁאֲרוּ')) { const b = R(3, 8), c = R(4, 12), a = b * c + R(10, 90); return { text: fill(t, { a, b, c }), answer: a - b * c }; }
    const b = R(3, 7), c = R(6, 12), a = R(5, 30); return { text: fill(t, { a, b, c }), answer: b * c + a };
  }
  const ops = { 1: ['+', '-'], 2: ['+', '-', '×'], 3: ['+', '-', '×', '÷'], 4: ['+', '-', '×', '÷', '×2'], 5: ['+', '-', '×2', '÷', '□'] }[L];
  const op = pickOne(ops);
  if (op === '+') {
    if (L === 1) { const a = R(10, 60), b = R(3, 35); return { eq: `${a} + ${b}`, answer: a + b }; }
    if (L === 2) { const a = R(15, 79), b = R(12, 99 - a); return { eq: `${a} + ${b}`, answer: a + b }; }
    const a = R(120, 680), b = R(95, 999 - a); return { eq: `${a} + ${b}`, answer: a + b };
  }
  if (op === '-') {
    if (L === 1) { const a = R(20, 99), b = R(3, a - 10); return { eq: `${a} − ${b}`, answer: a - b }; }
    if (L === 2) { const a = R(31, 99), b = R(12, a - 5); return { eq: `${a} − ${b}`, answer: a - b }; }
    const a = R(300, 999), b = R(105, a - 50); return { eq: `${a} − ${b}`, answer: a - b };
  }
  if (op === '×') { const t = L === 2 ? pickOne([2, 5, 10]) : R(2, 10), b = R(2, 10); return { eq: `${t} × ${b}`, answer: t * b }; }
  if (op === '×2') { const a = R(12, L >= 5 ? 49 : 25), b = R(3, 9); return { eq: `${a} × ${b}`, answer: a * b }; }
  if (op === '÷') { const b = R(2, L >= 5 ? 12 : 10), q = R(2, 10); return { eq: `${b * q} ÷ ${b}`, answer: q }; }
  // □ – המספר החסר
  const a = R(25, 480), s = a + R(30, 400); return { eq: `□ + ${s - a} = ${s}`, answer: a, missing: true };
}

